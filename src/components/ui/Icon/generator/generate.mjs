import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";

const source = await readFile(
	new URL("icon-sheet.svg", import.meta.url),
	"utf8"
);
const manifest = JSON.parse(
	await readFile(new URL("manifest.json", import.meta.url), "utf8")
);
const output = new URL("../", import.meta.url);
const prettier = await resolveConfig(fileURLToPath(output));
const banner = "// Generated by pnpm generate:icons. Do not edit by hand.\n";

// The outlined labels are not text: each outer array is a group, each inner
// entry a row. The 24px copies have centres (108 + group * 432, 48 + row * 80).
const cells = manifest.flatMap((names, group) =>
	names.map((name, row) => ({
		name,
		group,
		component: `${name.replace(/(^|-)([a-z])/g, (_, _separator, letter) => letter.toUpperCase())}Icon`,
		x: 96 + group * 432,
		y: 36 + row * 80,
		elements: [],
	}))
);
if (cells.length !== 77 || new Set(cells.map(({ name }) => name)).size !== 77) {
	throw new Error("The manifest must contain 77 unique design names.");
}

// A deliberately restricted reader for this flat design export, not a general
// XML parser. Reject structural changes rather than silently lose artwork.
const attributes = (text) => {
	const result = Object.fromEntries(
		[...text.matchAll(/([\w:-]+)="([^"]*)"/g)].map(([, name, value]) => [
			name,
			value,
		])
	);
	if (text.replace(/([\w:-]+)="([^"]*)"/g, "").trim()) {
		throw new Error(`Unsupported SVG attributes: ${text}`);
	}
	return result;
};
const allowed = new Set([
	"d",
	"cx",
	"cy",
	"r",
	"fill",
	"stroke",
	"stroke-width",
	"stroke-linecap",
	"stroke-linejoin",
	"stroke-miterlimit",
	"fill-rule",
	"clip-rule",
]);
for (const match of source.matchAll(/<([^>]+)>/g)) {
	const tag = match[1];
	if (tag === "/svg") continue;
	if (tag.startsWith("svg ")) {
		const root = attributes(tag.slice(4));
		if (root.viewBox !== "0 0 2560 1256" || root.fill !== "none") {
			throw new Error("Expected the 2560×1256 design sheet with fill=none.");
		}
		continue;
	}
	if (tag === 'rect width="2560" height="1256" fill="white"/') continue;
	const element = /^(path|circle)\s+([\s\S]*?)\/$/.exec(tag);
	if (!element) throw new Error(`Unsupported SVG element: ${tag.slice(0, 80)}`);
	const [, type, text] = element;
	const attrs = attributes(text);
	for (const name of Object.keys(attrs)) {
		if (!allowed.has(name))
			throw new Error(`Unsupported SVG attribute: ${name}`);
	}
	// Every path begins with an absolute moveto inside its cell. A circle's
	// centre serves the same purpose. The 16px/32px copies and labels fall outside.
	const start =
		type === "path"
			? /^M\s*(-?[\d.]+)[\s,]+(-?[\d.]+)/.exec(attrs.d)
			: [null, attrs.cx, attrs.cy];
	if (!start) throw new Error("Expected an absolute initial SVG moveto.");
	const x = Number(start[1]);
	const y = Number(start[2]);
	const cell = cells.find(
		(cell) => x >= cell.x && x <= cell.x + 24 && y >= cell.y && y <= cell.y + 24
	);
	if (!cell) continue;
	const jsx = Object.entries(attrs)
		.map(([name, value]) => {
			const prop = name.replace(/-([a-z])/g, (_, letter) =>
				letter.toUpperCase()
			);
			const colour = name === "fill" || name === "stroke";
			return [prop, colour && value !== "none" ? "currentColor" : value];
		})
		.sort(([left], [right]) => (left < right ? -1 : left > right ? 1 : 0))
		.map(([name, value]) => `${name}=${JSON.stringify(value)}`)
		.join(" ");
	cell.elements.push(`<${type} ${jsx} />`);
}

// Translate a group instead of rounding rewritten path coordinates: this keeps
// every source curve, circle, stroke width, cap and join exactly intact.
const files = cells.map(({ component, x, y, elements }) => {
	if (!elements.length)
		throw new Error(`No 24px geometry found for ${component}.`);
	return {
		name: `${component}.tsx`,
		code: `${banner}
import { useId } from "react";
import type { FunctionComponent, Heroicon } from "@/common/types";

export const ${component}: Heroicon = ({ title, titleId, ...props }): FunctionComponent => {
  const generatedId = useId();
  const accessibleTitleId = titleId ?? generatedId;
  return (
  <svg aria-hidden={title ? undefined : true} aria-labelledby={title ? accessibleTitleId : undefined} fill="none" role={title ? "img" : undefined} viewBox="0 0 24 24" xmlns="http://www.w3.org/2000/svg" {...props}>
    {title ? <title id={accessibleTitleId}>{title}</title> : null}
    <g transform="translate(-${x} -${y})">
      ${elements.join("\n")}
    </g>
  </svg>
  );
};
`,
	};
});
// Tests and the gallery read export names from here instead of re-deriving them.
const catalogue = manifest.map((_, group) =>
	cells
		.filter((cell) => cell.group === group)
		.map(({ name, component }) => ({ name, exportName: component }))
);
files.push({
	name: "generator/catalogue.json",
	code: JSON.stringify(catalogue),
	parser: "json",
});
files.push({
	name: "index.ts",
	code:
		banner +
		cells
			.map(({ component }) => `export { ${component} } from "./${component}";`)
			.join("\n"),
});
const formatted = await Promise.all(
	files.map(async ({ name, code, parser = "typescript" }) => ({
		name,
		code: await format(code, { ...prettier, parser }),
	}))
);
await Promise.all(
	formatted.map(({ name, code }) => writeFile(new URL(name, output), code))
);
console.log(`Generated ${cells.length} icons, their barrel and catalogue.`);
