// Generates src/features/workspace/permissionContract.generated.ts from the
// API's permission contract (contracts/permission-catalog.json, a byte copy of
// hrms-backend-v2/contracts/permission-catalog.json).
//
//   node scripts/generate-permission-contract.mjs          write the module
//   node scripts/generate-permission-contract.mjs --check  fail if it is stale
//
// The contract is validated before anything is written, and the API's order
// is kept as is: it is the order every editor shows.
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";

const CONTRACT = new URL("../contracts/permission-catalog.json", import.meta.url);
const OUTPUT = new URL(
	"../src/features/workspace/permissionContract.generated.ts",
	import.meta.url
);
const SCHEMA_VERSION = 1;
const SCOPES = ["COMPANY", "BRANCH", "DEPARTMENT"];
const KEY = /^[a-z_]+:[a-z_]+$/;

const fail = (message) => {
	throw new Error(`permission contract: ${message}`);
};

const stringArray = (value, where) => {
	if (!Array.isArray(value) || value.some((item) => typeof item !== "string"))
		fail(`${where} must be an array of strings`);
	if (new Set(value).size !== value.length) fail(`${where} repeats a value`);
	return value;
};

/** Checks the contract's shape and meaning; returns the definitions in contract order. */
const validate = (contract) => {
	if (contract === null || typeof contract !== "object")
		fail("the file must hold a JSON object");
	if (contract.schemaVersion !== SCHEMA_VERSION)
		fail(
			`schemaVersion ${String(contract.schemaVersion)} is not supported (expected ${SCHEMA_VERSION})`
		);
	if (!Array.isArray(contract.permissions) || contract.permissions.length === 0)
		fail("permissions must be a non-empty array");
	const keys = new Set();
	const definitions = contract.permissions.map((entry, index) => {
		const where = `permissions[${index}]`;
		if (entry === null || typeof entry !== "object")
			fail(`${where} must be an object`);
		const { key, resource, action } = entry;
		if (typeof key !== "string" || !KEY.test(key))
			fail(`${where}.key ${JSON.stringify(key)} is not resource:action`);
		if (keys.has(key)) fail(`${key} is listed twice`);
		keys.add(key);
		if (`${resource}:${action}` !== key)
			fail(`${key} has resource ${resource} and action ${action}`);
		const assignableScopes = stringArray(
			entry.assignableScopes,
			`${key}.assignableScopes`
		);
		if (assignableScopes.length === 0)
			fail(`${key} can't be assigned anywhere`);
		for (const scope of assignableScopes)
			if (!SCOPES.includes(scope))
				fail(`${key} has unknown scope ${JSON.stringify(scope)}`);
		const prerequisites = stringArray(
			entry.prerequisites,
			`${key}.prerequisites`
		);
		if (prerequisites.includes(key)) fail(`${key} requires itself`);
		return { key, resource, action, assignableScopes, prerequisites };
	});
	for (const { key, prerequisites } of definitions)
		for (const required of prerequisites)
			if (!keys.has(required))
				fail(`${key} requires ${required}, which is not in the contract`);
	// Prerequisites must not loop, or no selection could ever satisfy them.
	const byKey = new Map(definitions.map((item) => [item.key, item]));
	const done = new Set();
	const visit = (key, path) => {
		if (path.includes(key))
			fail(`prerequisites loop: ${[...path, key].join(" -> ")}`);
		if (done.has(key)) return;
		for (const required of byKey.get(key).prerequisites)
			visit(required, [...path, key]);
		done.add(key);
	};
	for (const { key } of definitions) visit(key, []);
	return definitions;
};

const source = await readFile(CONTRACT, "utf8");
const definitions = validate(JSON.parse(source));
const checksum = createHash("sha256").update(source).digest("hex");
const literal = (value) => JSON.stringify(value, null, "\t");
const generated = `// Generated by \`pnpm generate:permissions\` from contracts/permission-catalog.json.
// Do not edit by hand: refresh the contract from the API and regenerate.

/** SHA-256 of the contract file this module was generated from. */
export const PERMISSION_CONTRACT_SHA256 = ${JSON.stringify(checksum)};

/** The places a permission can be assigned at, widest first. */
export const ASSIGNABLE_SCOPES = ${literal(SCOPES)} as const;

/** Every permission the API knows, in the API's order. */
export const PERMISSION_DEFINITIONS = ${literal(definitions)} as const;

/** One permission's definition. */
export type PermissionDefinition = (typeof PERMISSION_DEFINITIONS)[number];

/** A permission the API knows; a typo fails to compile. */
export type PermissionKey = PermissionDefinition["key"];

/** Every permission key, in the API's order. */
export const PERMISSION_KEYS = ${literal(definitions.map(({ key }) => key))} as const;
`;
const output = fileURLToPath(OUTPUT);
const formatted = await format(generated, {
	...(await resolveConfig(output)),
	filepath: output,
});

if (process.argv.includes("--check")) {
	const existing = await readFile(OUTPUT, "utf8").catch(() => "");
	if (existing !== formatted) {
		console.error(
			"permissionContract.generated.ts is out of date with contracts/permission-catalog.json. Run `pnpm generate:permissions`."
		);
		process.exit(1);
	}
	console.log(
		`Permission contract up to date (${definitions.length} permissions).`
	);
} else {
	await writeFile(OUTPUT, formatted);
	console.log(
		`Wrote ${definitions.length} permissions to permissionContract.generated.ts.`
	);
}
